# известная протяжённость (для сверки): Транссиб Москва — Владивосток 9 289 км, БАМ Тайшет — Советская Гавань 4 287 км
REF_KM = {code: km for code, _, _, _, km, _ in MAINLINES if km}


DETOUR = 1.45


def haversine(la1, lo1, la2, lo2):
    p = np.radians
    x = np.sin(p(la2 - la1) / 2) ** 2 + np.cos(p(la1)) * np.cos(p(la2)) * np.sin(p(lo2 - lo1) / 2) ** 2
    return float(2 * 6371 * np.arcsin(np.sqrt(x)))


def main():
    g = json.loads((OUT / "rail_graph.json").read_text(encoding="utf-8"))
    nodes, E = g["nodes"], np.array(g["edges"])
    idx = {e: i for i, e in enumerate(nodes)}
    n = len(nodes)
    M = csr_matrix((E[:, 2] + 1e-6, (E[:, 0].astype(int), E[:, 1].astype(int))), shape=(n, n))
    rows_st = list(csv.DictReader(open(OUT / "stations.csv", encoding="utf-8-sig"), delimiter=";"))
    names = {r["esr"]: r["name"] for r in rows_st}
    pos = {r["esr"]: (float(r["lat"]), float(r["lon"])) for r in rows_st if r["lat"]}
    rows, bad = [], 0
    for code, name, _, way, _, _ in MAINLINES:
        total, members = 0.0, {}
        # None в списке опор — разрыв: часть хода идёт по другой магистрали (ТАЖМ — по Транссибу);
        # километраж — от начала своей части (её первой опорной станции)
        parts, cur = [], []
        for w in way:
            if w is None:
                parts.append(cur); cur = []
            else:
                cur.append(w)
        parts.append(cur)
        for part in parts:
            km0, origin = 0.0, part[0][1]
            for (a, an), (b, bn) in zip(part, part[1:]):
                if a not in idx or b not in idx:
                    sys.exit(f"{name}: опорной станции нет в графе: {a if a not in idx else b} {an if a not in idx else bn}")
                if names.get(a) != an or names.get(b) != bn:
                    print(f"  {name}: название опоры в справочнике другое: {a} «{names.get(a)}» / {b} «{names.get(b)}»")
                d, pr = dijkstra(M, directed=False, indices=idx[a], return_predecessors=True)
                if not np.isfinite(d[idx[b]]):
                    sys.exit(f"{name}: нет пути {an} — {bn}")
                # объезд: путь по сети намного длиннее прямой — разрыв в графе или опоры не по порядку
                if a in pos and b in pos and d[idx[b]] > haversine(*pos[a], *pos[b]) * DETOUR + 25:
                    print(f"  ВНИМАНИЕ {name}: {an} — {bn} {d[idx[b]]:.0f} км по сети при {haversine(*pos[a], *pos[b]):.0f} км по прямой")
                path, j = [], idx[b]
                while j >= 0:
                    path.append(j); j = pr[j]
                for j in reversed(path):
                    e = nodes[j]
                    if "@" not in e and e not in members:
                        members[e] = (round(km0 + d[j]), origin)
                km0 += d[idx[b]]
            total += km0
        ref = REF_KM.get(code)
        note = f", справочно {ref} км ({(total - ref) / ref:+.1%})" if ref else ""
        if ref and abs(total - ref) / ref > 0.03:
            bad += 1
        print(f"{name}: {len(members)} станций, {total:.0f} км по тарифным участкам{note}")
        rows += [(e, code, km, origin) for e, (km, origin) in members.items()]
    with open(OUT / "mainlines.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f, delimiter=";")
        w.writerow(["esr", "line", "km", "from"])
        w.writerows(rows)
    print(f"{OUT / 'mainlines.csv'}: {len(rows)} строк" + (f"; расхождение с известной длиной > 3%: {bad}" if bad else ""))

if __name__ == "__main__":
    main()
